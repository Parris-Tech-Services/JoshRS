                ("elid_", "elid"),
                ("nardah", "elid"),
                ("devious", "devious"),
                ("handsand", "handsand"),
                ("enakh", "enakh"),
                ("fever_", "fever"),
                ("harmless", "fever"),
                ("fairy_", "fairy_farmers"),
                ("100_", "hundred_main"),
                ("hundred_", "hundred_main"),
                ("soulbane", "soulbane"),
                ("rag_", "rag"),
