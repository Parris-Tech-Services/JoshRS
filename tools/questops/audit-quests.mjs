#!/usr/bin/env node
// Structural audit of every quest in a revision-274 content checkout.
//
// This answers "which quests are structurally incomplete" without claiming any of them
// play correctly. It checks the things that make a quest *possible*:
//
//   VARP     a configs/*.varp exists, so stage can persist
//   JOURNAL  a `questlist:` handler exists, so the quest appears in the journal
//   REWARD   an XP or item reward is granted
//   WIRED    some file outside the quest directory references one of its labels, so an
//            NPC or object can actually reach the logic
//
// It deliberately does NOT try to judge dialogue wording. That needs a human comparing
// against the wiki and a real playthrough.
//
// Usage:
//   audit-quests.mjs <content-dir> [--out docs/quests/QUEST_AUDIT.md]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const contentDir = process.argv[2];
if (!contentDir) {
    console.error('usage: audit-quests.mjs <content-dir> [--out FILE]');
    process.exit(2);
}
const outIdx = process.argv.indexOf('--out');
const outFile = outIdx > 0 ? process.argv[outIdx + 1] : null;

const questsDir = join(contentDir, 'scripts/quests');
const scriptsRoot = join(contentDir, 'scripts');

function walk(dir, ext, acc = []) {
    if (!existsSync(dir)) return acc;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const p = join(dir, entry.name);
        if (entry.isDirectory()) walk(p, ext, acc);
        else if (entry.name.endsWith(ext)) acc.push(p);
    }
    return acc;
}

// One pass over the tree: every rs2 file, kept in memory for the WIRED check.
const allScripts = walk(scriptsRoot, '.rs2').map((p) => ({ path: p, text: readFileSync(p, 'utf8') }));
const allText = allScripts.map((s) => s.text).join('\n');

const SKIP = new Set(['interfaces', '_test', '_unpack']);
const questDirs = readdirSync(questsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((n) => !SKIP.has(n));

const rows = [];
for (const name of questDirs.sort()) {
    const dir = join(questsDir, name);
    const scripts = walk(join(dir, 'scripts'), '.rs2');
    const configs = existsSync(join(dir, 'configs')) ? readdirSync(join(dir, 'configs')) : [];
    const text = scripts.map((f) => readFileSync(f, 'utf8')).join('\n');

    const labels = [...text.matchAll(/\[label,([a-z0-9_]+)\]/gi)].map((m) => m[1]);
    const hasVarp = configs.some((c) => c.endsWith('.varp'));
    const hasJournal = /questlist:/i.test(text);
    const hasReward = /stat_advance|inv_add|send_quest_complete/i.test(text);
    // Wired if any label is referenced as `@label;` from a file outside this quest.
    // Quests with no labels cannot be judged this way, so the check is N/A rather than a gap.
    const external = allScripts.filter((s) => !s.path.startsWith(dir));
    const wired = labels.length === 0
        ? null
        : labels.some((l) => external.some((s) => s.text.includes(`@${l};`)));
    const todos = (text.match(/todo|fixme|revisit later/gi) ?? []).length;

    rows.push({
        name,
        scripts: scripts.length,
        labels: labels.length,
        hasVarp,
        hasJournal,
        hasReward,
        wired,
        todos
    });
}

const missing = (r) => [
    !r.hasVarp && 'VARP',
    !r.hasJournal && 'JOURNAL',
    !r.hasReward && 'REWARD',
    r.wired === false && 'WIRED'
].filter(Boolean);

const lines = [];
lines.push('# Quest structural audit');
lines.push('');
lines.push('Generated by `tools/questops/audit-quests.mjs`. Do not hand-edit.');
lines.push('');
lines.push('This checks that a quest is **structurally capable** of working. It says nothing about');
lines.push('whether the dialogue matches the wiki, or whether the quest plays correctly — those need a');
lines.push('human and a real playthrough. A quest missing a flag below is definitely broken; a quest');
lines.push('with every flag is only *not obviously broken*.');
lines.push('');
lines.push(`Source: \`${questsDir}\``);
lines.push('');
lines.push('| Quest | scripts | labels | VARP | JOURNAL | REWARD | WIRED | TODOs | Missing |');
lines.push('|---|---|---|---|---|---|---|---|---|');

let clean = 0;
for (const r of rows) {
    const m = missing(r);
    if (m.length === 0) clean++;
    const tick = (b) => (b === null ? 'n/a' : b ? 'yes' : '**no**');
    lines.push(
        `| \`${r.name}\` | ${r.scripts} | ${r.labels} | ${tick(r.hasVarp)} | ${tick(r.hasJournal)} | ${tick(r.hasReward)} | ${tick(r.wired)} | ${r.todos} | ${m.join(', ') || '—'} |`
    );
}

lines.push('');
lines.push('## Summary');
lines.push('');
lines.push(`- quests: **${rows.length}**`);
lines.push(`- structurally complete: **${clean}**`);
lines.push(`- with at least one gap: **${rows.length - clean}**`);
lines.push('');
lines.push('### Priority list (most gaps first)');
lines.push('');
for (const r of [...rows].sort((a, b) => missing(b).length - missing(a).length).slice(0, 20)) {
    const m = missing(r);
    if (m.length) lines.push(`- \`${r.name}\` — missing ${m.join(', ')}`);
}
lines.push('');

const report = lines.join('\n');
if (outFile) {
    writeFileSync(outFile, report);
    console.log(`wrote ${outFile}`);
} else {
    console.log(report);
}
console.log(`audited ${rows.length} quests, ${clean} structurally complete`);
