#!/usr/bin/env node
// Every quest must be able to complete.
//
// A quest directory can look perfectly healthy - it has a journal, a varp, reward lines and
// dialogue - while containing no `send_quest_complete` call at all, in which case the player
// can do every step and still never finish it. That failure is invisible to a structural audit
// that only checks for the presence of files.
//
// This check answers one question per quest: **is there a path to completion?**
//
// It also verifies that every `questlist:<id>` a quest completes is backed by a journal handler
// `[if_button,questlist:<id>]`, because a completion that writes to an unknown entry can leave
// the quest permanently "in progress" in the journal.
//
// Known exception: miniquests (e.g. Alfred Grimhand's Barcrawl) have no quest points, no
// journal entry and no completion call by design. They are reported separately, not as failures.
//
// Usage: check-completion-paths.mjs <content-dir> [--out FILE]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const contentDir = process.argv[2];
if (!contentDir) {
    console.error('usage: check-completion-paths.mjs <content-dir> [--out FILE]');
    process.exit(2);
}
const outIdx = process.argv.indexOf('--out');
const outFile = outIdx > 0 ? process.argv[outIdx + 1] : null;

// Miniquests legitimately have no quest points, journal or completion call.
const MINIQUESTS = new Set(['quest_barcrawl']);
const SKIP = new Set(['interfaces', '_test', '_unpack']);

const questsRoot = join(contentDir, 'scripts/quests');
const dirs = readdirSync(questsRoot, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((n) => n.startsWith('quest_') && !SKIP.has(n));

function scriptsOf(dir) {
    const sdir = join(questsRoot, dir, 'scripts');
    if (!existsSync(sdir)) return '';
    return readdirSync(sdir)
        .filter((f) => f.endsWith('.rs2'))
        .map((f) => readFileSync(join(sdir, f), 'utf8'))
        .join('\n');
}

// One pass over the tree for journal handlers, including those outside the quest directory.
const allJournalIds = new Set();
function walk(dir) {
    if (!existsSync(dir)) return;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = join(dir, e.name);
        if (e.isDirectory()) walk(p);
        else if (e.name.endsWith('.rs2')) {
            const txt = readFileSync(p, 'utf8');
            for (const m of txt.matchAll(/\[if_button,questlist:([a-z_0-9]+)\]/g)) allJournalIds.add(m[1]);
        }
    }
}
walk(join(contentDir, 'scripts'));

const rows = [];
for (const dir of dirs.sort()) {
    const txt = scriptsOf(dir);
    const completes = [...txt.matchAll(/send_quest_complete\(questlist:([a-z_0-9]+)/g)].map((m) => m[1]);
    const progresses = [...txt.matchAll(/send_quest_progress(?:_colour)?\(questlist:([a-z_0-9]+)/g)].map((m) => m[1]);
    const isMini = MINIQUESTS.has(dir);
    const missingJournal = completes.filter((id) => !allJournalIds.has(id));
    rows.push({
        dir,
        isMini,
        completes,
        progresses,
        missingJournal,
        ok: isMini ? completes.length === 0 : completes.length > 0 && missingJournal.length === 0
    });
}

const failures = rows.filter((r) => !r.ok);
const minis = rows.filter((r) => r.isMini);

const lines = [];
lines.push('# Quest completion-path check');
lines.push('');
lines.push('Generated by `tools/questops/check-completion-paths.mjs`.');
lines.push('');
lines.push('A quest can have every file a structural audit looks for and still contain **no**');
lines.push('`send_quest_complete` call — meaning the player can do every step and never finish it.');
lines.push('This check tests only that a completion path exists and that its journal entry is real.');
lines.push('');
lines.push(`- quests checked: **${rows.length}**`);
lines.push(`- with a completion path: **${rows.filter((r) => r.completes.length > 0).length}**`);
lines.push(`- miniquests (no completion by design): **${minis.length}**`);
lines.push(`- failures: **${failures.length}**`);
lines.push('');
if (failures.length) {
    lines.push('## Failures');
    lines.push('');
    for (const f of failures) {
        const why = f.completes.length === 0
            ? 'no `send_quest_complete` call'
            : `completes unknown journal id(s): ${f.missingJournal.join(', ')}`;
        lines.push(`- \`${f.dir}\` — ${why}`);
    }
} else {
    lines.push('## Failures');
    lines.push('');
    lines.push('_None._');
}
const quirky = rows.filter((r) => r.completes.length && r.completes.some((c) => !r.dir.includes(c) && !c.includes(r.dir.replace('quest_', ''))));
if (quirky.length) {
    lines.push('');
    lines.push('## Completion ids that do not match the directory name');
    lines.push('');
    lines.push('Not errors — the journal entry is simply named differently — but worth knowing when');
    lines.push('searching by directory.');
    lines.push('');
    for (const q of quirky) lines.push(`- \`${q.dir}\` → \`questlist:${q.completes[0]}\``);
}

const report = lines.join('\n');
if (outFile) {
    writeFileSync(outFile, report);
    console.log(`wrote ${outFile}`);
} else {
    console.log(report);
}
console.log(`checked ${rows.length} quests, ${failures.length} failures`);
