#!/usr/bin/env node
// Reconcile the four places JoshRS tracks quest work into one matrix.
//
//   --world <dir>     content/scripts/quests of a running world (e.g. ~/lc274/content/scripts/quests)
//   --patches <dir>   JoshRS content-patches/rs377/scripts/quests
//   --bots <dir>      tools/rs-sdk-quests/quests
//   --status <file>   tools/rs-sdk-quests/QUEST_STATUS.md
//   --out <file>      markdown output
//
// Matching is deliberately heuristic and says so in the output: the world uses
// `quest_cook`, bots use `cooks-assistant.ts`, and STATUS uses display names like
// "Cook's Assistant". Anything that cannot be matched is listed explicitly rather
// than silently dropped.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { basename, join } from 'node:path';

function arg(name, fallback) {
    const i = process.argv.indexOf(`--${name}`);
    return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const worldDir = arg('world', null);
const patchDir = arg('patches', null);
const botDir = arg('bots', null);
const statusFile = arg('status', null);
const outFile = arg('out', 'docs/QUEST_MATRIX.md');

function listDirs(dir) {
    if (!dir || !existsSync(dir)) return [];
    return readdirSync(dir, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name)
        .filter((n) => n !== 'interfaces');
}

function listFiles(dir, ext) {
    if (!dir || !existsSync(dir)) return [];
    return readdirSync(dir, { withFileTypes: true })
        .filter((d) => d.isFile() && d.name.endsWith(ext))
        .map((d) => basename(d.name, ext));
}

/** Loose key so quest_cook / cooks-assistant / "Cook's Assistant" can meet. */
function key(name) {
    return name
        .toLowerCase()
        .replace(/^quest_/, '')
        .replace(/^the /, '')
        .replace(/[^a-z0-9]/g, '')
        .replace(/assistant$/, '')
        .replace(/^the(?=[a-z])/, '');
}

function parseStatus(file) {
    if (!file || !existsSync(file)) return [];
    const rows = [];
    for (const line of readFileSync(file, 'utf8').split('\n')) {
        const m = line.match(/^\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|\s*([^|]+?)\s*\|(.*)\|$/);
        if (!m) continue;
        const name = m[1].trim();
        if (/^quest$/i.test(name) || /^-+$/.test(name)) continue;
        rows.push({ name, keyRaw: m[2].trim(), status: m[3].trim().toLowerCase(), notes: m[4].trim() });
    }
    return rows;
}

const world = listDirs(worldDir).map((d) => ({ dir: d, k: key(d) }));
const patches = listDirs(patchDir).map((d) => ({ dir: d, k: key(d) }));
const bots = listFiles(botDir, '.ts').map((d) => ({ file: d, k: key(d) }));
const status = parseStatus(statusFile).map((r) => ({ ...r, k: key(r.name) }));

const best = (list, k, field) => {
    if (!k) return null;
    const exact = list.find((x) => x.k === k);
    if (exact) return exact[field];
    const partial = list.find((x) => x.k && (x.k.includes(k) || k.includes(x.k)) && Math.min(x.k.length, k.length) >= 4);
    return partial ? partial[field] : null;
};

// STATUS supplies the authoritative player-facing names and short keys. Those keys
// are what actually connect `quest_priest` to the bot script `restless-ghost`, which
// no amount of string similarity would discover.
function statusForWorld(w) {
    const shortKey = w.k;
    return status.find((s) => {
        const byKey = key(s.keyRaw.replace(/^-$/, '')) === shortKey;
        const byName = s.k === shortKey;
        // cooks -> quest_cook (singular world dir)
        const singular = shortKey === 'cook' && key(s.keyRaw) === 'cooks';
        return byKey || byName || singular;
    }) ?? null;
}

function botForStatus(s) {
    if (!s) return null;
    const exact = bots.find((b) => b.k === s.k);
    if (exact) return exact.file;
    const partial = bots.find((b) => b.k && (b.k.includes(s.k) || s.k.includes(b.k)) && Math.min(b.k.length, s.k.length) >= 5);
    return partial ? partial.file : null;
}

const rows = world.map((w) => {
    const tracked = statusForWorld(w);
    return {
        quest: w.dir,
        patch: best(patches, w.k, 'dir'),
        bot: botForStatus(tracked) ?? best(bots, w.k, 'file'),
        tracked
    };
});

const botOnly = bots.filter((b) => !rows.some((r) => r.bot === b.file));
const patchOnly = patches.filter((p) => !rows.some((r) => r.patch === p.dir));
const statusOnly = status.filter((s) => !rows.some((r) => r.tracked && r.tracked.name === s.name));

const yes = (v) => (v ? 'yes' : '—');

const lines = [];
lines.push('# Quest matrix — one honest state per quest');
lines.push('');
lines.push('Generated by `tools/quest-audit/build-matrix.mjs`. Do not hand-edit; regenerate.');
lines.push('');
lines.push('Matching between the four trackers is **heuristic** (`quest_cook` / `cooks-assistant.ts` /');
lines.push('"Cook\'s Assistant" are matched on a normalised key). Unmatched entries are listed at the');
lines.push('end rather than dropped, so nothing silently disappears.');
lines.push('');
lines.push('A quest marked `done` in `QUEST_STATUS.md` was proven on a **revision 225** server.');
lines.push('That is not evidence it works in the 274 world you can play, nor on 377.');
lines.push('');
lines.push(`## Quests present in the world (${rows.length})`);
lines.push('');
lines.push('| Quest script | 377 patch | Bot script | Bot status |');
lines.push('|---|---|---|---|');
for (const r of rows.sort((a, b) => a.quest.localeCompare(b.quest))) {
    lines.push(`| \`${r.quest}\` | ${r.patch ? `\`${r.patch}\`` : '—'} | ${r.bot ? `\`${r.bot}\`` : '—'} | ${r.tracked ? r.tracked.status : 'untracked'} |`);
}

lines.push('');
lines.push('## Coverage');
lines.push('');
const withBot = rows.filter((r) => r.bot).length;
const withPatch = rows.filter((r) => r.patch).length;
const tracked = rows.filter((r) => r.tracked).length;
lines.push(`- world quests: **${rows.length}**`);
lines.push(`- with a bot script: **${withBot}** (${rows.length - withBot} have none)`);
lines.push(`- with a 377 patch: **${withPatch}**`);
lines.push(`- present in \`QUEST_STATUS.md\`: **${tracked}**`);
lines.push(`- bot scripts with no matching world quest: **${botOnly.length}**`);
lines.push(`- 377 patches with no matching world quest: **${patchOnly.length}**`);
lines.push(`- status rows with no matching world quest: **${statusOnly.length}**`);

if (botOnly.length) {
    lines.push('');
    lines.push('## Bot scripts with no matching world quest');
    lines.push('');
    botOnly.forEach((b) => lines.push(`- \`${b.file}\``));
}
if (patchOnly.length) {
    lines.push('');
    lines.push('## 377 patches with no matching world quest');
    lines.push('');
    patchOnly.forEach((p) => lines.push(`- \`${p.dir}\``));
}
if (statusOnly.length) {
    lines.push('');
    lines.push('## Status rows with no matching world quest');
    lines.push('');
    statusOnly.forEach((s) => lines.push(`- ${s.name} (${s.status})`));
}

lines.push('');
const overlap = world.filter((w) => patches.some((p) => p.k === w.k)).length;

lines.push('## Gaps that matter most');
lines.push('');
lines.push('1. Quests with **no bot script** cannot be verified again, so a regression would be invisible.');
lines.push('2. Quests **marked done on 225** have not been re-proven in the 274 world.');
lines.push(`3. **The 377 patch set and this world barely overlap** (${overlap} of ${patches.length} patch dirs match a world quest).`);
lines.push('   Revision 274 predates most of those quests, so bot evidence gathered on 274 says');
lines.push('   nothing about the 377 patches, and vice versa. Two separate campaigns.');
lines.push('4. Every `—` in the bot column is a quest that has never been driven end to end here.');
lines.push('');

writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${outFile}`);
console.log(`world=${rows.length} bot=${withBot} patch=${withPatch} tracked=${tracked} botOnly=${botOnly.length} patchOnly=${patchOnly.length} statusOnly=${statusOnly.length}`);
