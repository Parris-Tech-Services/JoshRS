import json,os,re,sys,collections
C=sys.argv[1]; R=json.load(open('ladder_rows.json'))
trig=set()
for root,ds,fs in os.walk(os.path.join(C,'scripts')):
    for f in fs:
        if f.endswith('.rs2'):
            for m in re.finditer(r'^\[(\w+),([^\]]+)\]',open(os.path.join(root,f),encoding='utf-8',errors='replace').read(),re.M): trig.add((m.group(1),m.group(2)))
lp={b:int(a) for a,b in (l.rstrip('\n').split('=',1) for l in open(os.path.join(C,'pack','loc.pack')) if '=' in l)}
lit=lambda lv,X,Z:f"{lv}_{X>>6}_{Z>>6}_{X&63}_{Z&63}"
EX={(e[0],e[1],tuple(e[2])) for e in json.load(open('ladder_exclude.json'))}
groups=collections.defaultdict(list); cases=[]; skipped=collections.Counter()
for r in R:
    nm,op,label=r['loc'],r['op'],r['label'].lower()
    if (f'aploc{op}',nm) in trig or (f'oploc{op}',nm) in trig: skipped['has-ap/op']+=1; continue
    if not re.search(r'(?i)ladder|trapdoor',r['name'] or ''): skipped['not-a-ladder']+=1; continue
    if not r['pairs']: skipped['unpaired']+=1; continue
    lv,X,Z=r['pos']
    if (nm,op,(lv,X,Z)) in EX: skipped['excluded']+=1; continue
    def best(kind):
        for k,p in r['pairs']:
            if k.startswith(kind):
                q=min(p,key=lambda q:abs(q[2]-X)+abs(q[3]-Z)); return q
    up,dn=best('up'),best('down')
    if label=='climb-up': up,dn=up,None
    elif label=='climb-down': up,dn=None,dn
    if up and dn:
        groups[(nm,op)].append(f"    case {lit(lv,X,Z)} : @nih_climb_choice({lit(lv,X,Z)}, {lit(*up[1:])}, {lit(*dn[1:])});")
        cases.append({'loc':lp[nm],'name':nm,'op':op,'x':X,'z':Z,'level':lv,'choice':True,'up':up[1:],'down':dn[1:]})
    else:
        t=up or dn; isup= t is up
        groups[(nm,op)].append(f"    case {lit(lv,X,Z)} : ~nih_climb({lit(lv,X,Z)}, {lit(*t[1:])}, {'true' if isup else 'false'});")
        cases.append({'loc':lp[nm],'name':nm,'op':op,'x':X,'z':Z,'level':lv,'expect':t[1:]})
out=["// Generated by tools/rs377-nothing-interesting: ladders/stairs placed on the 377 map that had no",
"// handler. Each case only exists where a matching climbable object was found on the floor above",
"// or below (or the dungeon level 6400 tiles north), so nobody is stranded. Unmatched spots keep",
"// the default message. Landing tile: same offset from the destination ladder as the player had",
"// from this one; if that is blocked, the nearest free tile around the destination ladder.",""]
for (nm,op),cs in sorted(groups.items()):
    out+= [f"[oploc{op},{nm}]","p_arrivedelay;","switch_coord (loc_coord) {",*cs,'    case default : mes("Nothing interesting happens.");',"}",""]
out+=["""[proc,nih_land](coord $from, coord $to)(coord)
def_coord $dest = movecoord(coord, sub(coordx($to), coordx($from)), sub(coordy($to), coordy($from)), sub(coordz($to), coordz($from)));
if (map_blocked($dest) = true) {
    $dest = map_findsquare($to, 1, 2, ^map_findsquare_lineofsight);
}
if (map_blocked($dest) = true) {
    $dest = map_findsquare($to, 1, 3, ^map_findsquare_none);
}
return($dest);

[proc,nih_climb](coord $from, coord $to, boolean $up)
~climb_ladder(~nih_land($from, $to), $up);

[label,nih_climb_choice](coord $from, coord $up, coord $down)
@ladder_options(~nih_land($from, $up), ~nih_land($from, $down));
"""]
open('nih_ladders.rs2','w').write('\n'.join(out)); json.dump(cases,open('ladder_cases.json','w'),indent=0)
print('handlers',len(groups),'cases',len(cases),'choice',sum(1 for c in cases if c.get('choice')),dict(skipped))
